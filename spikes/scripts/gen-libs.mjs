// Generates src/ts-libs.generated.ts: every TypeScript lib file needed for
// `lib: ["es2022"]`, exported as strings so the Worker can serve them from memory.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const libDir = join(root, "node_modules/typescript/lib");
const wanted = /^lib\.(es5|es20(15|16|17|18|19|20|21|22)(\.[a-z.]+)?|decorators(\.legacy)?)\.d\.ts$/;

const names = readdirSync(libDir)
	.filter((name) => wanted.test(name) && !name.endsWith(".full.d.ts"))
	.sort();

const entries = names.map(
	(name) => `\t${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(libDir, name), "utf8"))},`,
);

writeFileSync(
	join(root, "src/ts-libs.generated.ts"),
	`// GENERATED by scripts/gen-libs.mjs. Do not edit.\nexport const TS_LIBS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`wrote ${names.length} lib files`);
