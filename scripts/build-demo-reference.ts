// Generates, inside demo-repo/:
//   premise/reference/<id>.patch.ts     each reference solution as a FileChanges object
//   premise/hidden-tests/<task>.test.ts each task's acceptance tests, for the A/B harness
// from demo-solutions/. Run with `npm run demo:reference`.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SOLUTIONS, type Solution } from "../demo-solutions/solutions";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "demo-repo");
const testSource = join(root, "demo-solutions/tests");
const referenceDir = join(repo, "premise/reference");
const hiddenDir = join(repo, "premise/hidden-tests");

function applyEdits(solution: Solution): Record<string, string> {
	const files: Record<string, string> = {};
	for (const edit of solution.edits) {
		const current = files[edit.file] ?? readFileSync(join(repo, edit.file), "utf8");
		const occurrences = current.split(edit.find).length - 1;
		if (occurrences !== 1) {
			throw new Error(`${solution.id}: expected exactly one match in ${edit.file}, found ${occurrences}, for:\n${edit.find}`);
		}
		files[edit.file] = current.replace(edit.find, () => edit.replace);
	}
	return files;
}

/** A test written for demo-repo/tests/ with its imports re-pointed for premise/hidden-tests/. */
function asHiddenTest(source: string): string {
	return source
		.replaceAll('from "../premise/assert.js"', 'from "../assert.js"')
		.replaceAll('from "../src/', 'from "../../src/')
		.replaceAll('from "./support.js"', 'from "../../tests/support.js"');
}

for (const dir of [referenceDir, hiddenDir]) {
	rmSync(dir, { recursive: true, force: true });
	mkdirSync(dir, { recursive: true });
}

for (const solution of SOLUTIONS) {
	const changes = applyEdits(solution);
	for (const test of solution.tests) {
		changes[`tests/${test}`] = readFileSync(join(testSource, test), "utf8");
	}
	const body = Object.entries(changes)
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([path, content]) => `\t${JSON.stringify(path)}: ${JSON.stringify(content)},`)
		.join("\n");
	writeFileSync(
		join(referenceDir, `${solution.id}.patch.ts`),
		[
			"// GENERATED by scripts/build-demo-reference.ts from demo-solutions/. Do not edit.",
			`// ${solution.summary}`,
			`export const meta = ${JSON.stringify({ id: solution.id, task: solution.task, appliesOn: solution.appliesOn })} as const;`,
			"",
			"/** Repo-relative path -> complete new file content. */",
			"const changes: Record<string, string | null> = {",
			body,
			"};",
			"",
			"export default changes;",
			"",
		].join("\n"),
	);
}

// One hidden test file per task. A task's trunk solution and its re-derived solution share the same tests.
const byTask = new Map<string, Set<string>>();
for (const solution of SOLUTIONS) {
	const tests = byTask.get(solution.task) ?? new Set<string>();
	solution.tests.forEach((test) => tests.add(test));
	byTask.set(solution.task, tests);
}
for (const [task, tests] of byTask) {
	if (tests.size !== 1) {
		throw new Error(`${task}: expected exactly one acceptance test file, got ${[...tests].join(", ")}`);
	}
	const [test] = [...tests] as [string];
	const header = `// GENERATED by scripts/build-demo-reference.ts from demo-solutions/tests/${test}. Do not edit.\n`;
	writeFileSync(join(hiddenDir, `${task}.test.ts`), header + asHiddenTest(readFileSync(join(testSource, test), "utf8")));
}

console.log(`wrote ${readdirSync(referenceDir).length} patches and ${readdirSync(hiddenDir).length} hidden tests`);
